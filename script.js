  /* -------------------------------- Search ------------------------------- */

  let searchIndex = [];

  function buildSearchIndex() {
    const clean = (s) => s.replace(/\s+/g, ' ').trim();
    searchIndex = [];

    $$('[data-view]').forEach((sec) => {
      const view = sec.dataset.view;
      if (view === 'events') return;
      const clone = sec.cloneNode(true);
      $$('iframe, script, style', clone).forEach((n) => n.remove());
      searchIndex.push({
        title: TITLES[view],
        page: TITLES[view],
        href: `#${view}`,
        text: clean(clone.textContent)
      });
    });

    $$('.event', eventsRoot).forEach((art) => {
      searchIndex.push({
        title: $('h2', art).textContent,
        page: 'Events',
        href: `#${art.id}`,
        text: clean(art.textContent)
      });
    });
  }

  function snippet(text, q) {
    const i = text.toLowerCase().indexOf(q);
    if (i < 0) return text.slice(0, 90) + (text.length > 90 ? '…' : '');
    const start = Math.max(0, i - 35);
    const end = Math.min(text.length, i + q.length + 55);
    return (start > 0 ? '…' : '') + text.slice(start, end) + (end < text.length ? '…' : '');
  }

  function runSearch() {
    const q = searchInput.value.trim().toLowerCase();
    searchResults.innerHTML = '';
    if (q.length < 2) return;

    const hits = searchIndex
      .filter((e) => e.title.toLowerCase().includes(q) || e.text.toLowerCase().includes(q))
      .slice(0, 8);

    if (!hits.length) {
      searchResults.innerHTML = '<li class="search-empty">No matches found.</li>';
      return;
    }
    searchResults.innerHTML = hits
      .map(
        (h) => `<li><a href="${h.href}"><strong>${escapeHtml(h.title)}</strong>
          <small>${escapeHtml(h.page)} · ${escapeHtml(snippet(h.text, q))}</small></a></li>`
      )
      .join('');
  }

  function openSearch() {
    searchPanel.hidden = false;
    searchToggle.setAttribute('aria-expanded', 'true');
    closeMenu();
    searchInput.focus();
  }
  function closeSearch() {
    if (searchPanel.hidden) return;
    searchPanel.hidden = true;
    searchToggle.setAttribute('aria-expanded', 'false');
  }

  searchToggle.addEventListener('click', () => (searchPanel.hidden ? openSearch() : closeSearch()));
  searchInput.addEventListener('input', runSearch);
  searchResults.addEventListener('click', (e) => {
    if (e.target.closest('a')) {
      closeSearch();
      searchInput.value = '';
      searchResults.innerHTML = '';
    }
  });

  document.addEventListener('keydown', (e) => {
    if (e.key !== 'Escape') return;
    if (!searchPanel.hidden) {
      closeSearch();
      searchToggle.focus();
    } else if (nav.classList.contains('is-open')) {
      closeMenu();
      menuToggle.focus();
    }
  });

