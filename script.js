  function staticEvents() {
    const photos = Array.isArray(window.ORIGINAL_PHOTOS) ? window.ORIGINAL_PHOTOS : [];
    return EVENTS.map((event) => ({
      id: event.id,
      title: event.title,
      eventDate: '',
      eventTime: '',
      venue: '',
      descriptionHtml: event.html || '',
      descriptionText: '',
      postDate: event.date || '',
      badges: event.badges || [],
      photos: photos
        .filter((photo) => photo.eventId === event.id)
        .map((photo, index) => ({ ...photo, id: `local-${event.id}-${index}` }))
    }));
  }

  function eventGroup(event) {
    if (!event.eventDate) return 'undated';
    return event.eventDate < new Date().toISOString().slice(0, 10) ? 'past' : 'upcoming';
  }

  function eventMeta(event) {
    const details = [];
    if (event.eventDate) details.push(`<p class="event-date">Event date: ${escapeHtml(event.eventDate)}</p>`);
    if (event.eventTime) details.push(`<p>Time: ${escapeHtml(event.eventTime)}</p>`);
    if (event.venue) details.push(`<p>Venue: ${escapeHtml(event.venue)}</p>`);
    if (event.postDate) details.push(`<p class="event-post-date">Post date: ${escapeHtml(event.postDate)}</p>`);
    return details.length ? `<div class="event-meta">${details.join('')}</div>` : '';
  }

  function eventGallery(event) {
    if (!event.photos || !event.photos.length) return '';
    return `<ul class="gallery" aria-label="Photos from ${escapeHtml(event.title)}">
      ${event.photos.map((photo, index) => `<li>
        <button class="thumb" type="button" data-event-id="${escapeHtml(event.id)}" data-photo-index="${index}" aria-label="View photo ${index + 1} of ${event.photos.length} from ${escapeHtml(event.title)}">
          <img src="${escapeHtml(photo.src)}" alt="${escapeHtml(photo.alt || event.title)}" loading="lazy" decoding="async">
        </button>
      </li>`).join('')}
    </ul>`;
  }

  function eventCard(event) {
    const badges = event.badges?.length
      ? `<div class="badge-grid">${event.badges.map((badge) =>
          `<div class="badge-card"><h3>${escapeHtml(badge.cls || '')}</h3><dl>${(badge.rows || [])
            .map(([key, value]) => `<div><dt>${escapeHtml(key)}</dt><dd>${escapeHtml(value)}</dd></div>`).join('')}</dl></div>`
        ).join('')}</div>`
      : '';
    const content = `<div class="event-text">${event.descriptionHtml || '<p>Additional event details are not listed in the available source.</p>'}</div>`;
    return `<article class="event" id="event-${escapeHtml(event.id)}" aria-labelledby="h-${escapeHtml(event.id)}">
      <h2 id="h-${escapeHtml(event.id)}">${escapeHtml(event.title)}</h2>
      ${eventMeta(event)}
      ${content}
      ${badges}
      ${eventGallery(event)}
      <div class="event-actions"><a class="btn" href="#event-details/${encodeURIComponent(event.id)}">View Full Details</a></div>
    </article>`;
  }

